const units: [RegExp, string][] = [
  [/^(\d+) feet$/i, '$1 רגל'],
  [/^(\d+) miles?$/i, '$1 מייל'],
  [/^(\d+) rounds?$/i, '$1 סבבים'],
  [/^(\d+) minutes?$/i, '$1 דקות'],
  [/^(\d+) hours?$/i, '$1 שעות'],
  [/^(\d+) days?$/i, '$1 ימים'],
]
const singles: Record<string, string> = {
  '1 round': 'סבב אחד', '1 minute': 'דקה', '1 hour': 'שעה', '1 day': 'יום', '1 mile': 'מייל',
  '1 action': 'פעולה', 'action': 'פעולה', '1 bonus action': 'פעולת בונוס', 'bonus action': 'פעולת בונוס',
  '1 reaction': 'תגובה', 'reaction': 'תגובה',
  self: 'עצמי', touch: 'מגע', sight: 'קו ראייה', unlimited: 'ללא הגבלה', special: 'מיוחד',
  instantaneous: 'מיידי', 'until dispelled': 'עד לביטול', 'until dispelled or triggered': 'עד לביטול או להפעלה',
}
const shapes: Record<string, string> = { radius: 'רדיוס', emanation: 'קרינה', cone: 'חרוט', line: 'קו', cube: 'קובייה', sphere: 'כדור' }

/** A single measure ("60 feet", "1 action", "Touch") in Hebrew, or undefined when it is not one. */
function measureHe(text: string): string | undefined {
  const s = text.trim().toLowerCase()
  if (singles[s]) return singles[s]
  for (const [re, out] of units) if (re.test(s)) return s.replace(re, out)
  return undefined
}

/**
 * Casting time, range or duration in Hebrew ("1 action" → "פעולה", "Self (30-foot cone)" → "עצמי (חרוט 30 רגל)",
 * "up to 1 minute" → "עד דקה"). Long trigger texts keep their Hebrew lead word and drop the English condition.
 * Returns the English text when the phrase is unknown (homebrew).
 */
export function spellMeasureHe(text: string): string {
  const s = text.replace(/\s+Component:.*$/i, '').trim()
  const direct = measureHe(s)
  if (direct) return direct
  const upTo = /^(?:concentration\s+)?up to (.+)$/i.exec(s)
  if (upTo) { const m = measureHe(upTo[1]); if (m) return `עד ${m}` }
  const area = /^self \((\d+)-foot (\w+)\)$/i.exec(s)
  if (area && shapes[area[2].toLowerCase()]) return `עצמי (${shapes[area[2].toLowerCase()]} ${area[1]} רגל)`
  const lead = /^(bonus action|reaction|action)\b,?\s*(.+)$/i.exec(s)
  if (lead) {
    const head = singles[lead[1].toLowerCase()]
    const rest = lead[2]
    if (/after (?:you )?hit/i.test(rest)) return `${head}, מיד אחרי פגיעה`
    if (/casting a spell/i.test(rest)) return `${head}, כשיצור מטיל לחש`
    if (/falls/i.test(rest)) return `${head}, כשיצור נופל`
    if (/taking damage/i.test(rest)) return `${head}, כשנפגעים`
    if (/hit by an attack/i.test(rest)) return `${head}, כשפוגעים בך`
    if (/overgrowth/i.test(rest)) return `${head} או 8 שעות`
    return head
  }
  return text
}
